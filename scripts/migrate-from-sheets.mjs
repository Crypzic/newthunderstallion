#!/usr/bin/env node
// One-time import of the old Google Sheets data into Supabase.
//
// 1. In the old Google Sheet, open each tab and use File → Download → CSV:
//      LISTINGS → listings.csv      VOTES → votes.csv (optional)
// 2. node scripts/migrate-from-sheets.mjs listings.csv [votes.csv] > supabase/import.sql
// 3. Paste supabase/import.sql into the Supabase SQL editor and run it
//    (after schema.sql).
//
// Old user accounts are not imported — passwords can't be carried over.
// Each listing keeps its old username; when that person signs up again with
// the same username, the listing is re-attached to their new account
// automatically (see handle_new_user in schema.sql).

import { readFileSync } from "node:fs";

const [listingsCsv, votesCsv] = process.argv.slice(2);
if (!listingsCsv) {
  console.error("usage: node scripts/migrate-from-sheets.mjs listings.csv [votes.csv] > supabase/import.sql");
  process.exit(1);
}

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows.filter((r) => r.some((c) => c.trim()));
  return body.map((r) => Object.fromEntries(header.map((h, i) => [h.trim(), (r[i] ?? "").trim()])));
}

const qs = (v) => `'${String(v ?? "").replace(/'/g, "''")}'`;
const ts = (v) => {
  const d = v ? new Date(v) : null;
  return d && !isNaN(d) ? `'${d.toISOString()}'` : "null";
};
const status = (s) => (/approv/i.test(s) ? "approved" : /reject/i.test(s) ? "rejected" : "pending");
const truthy = (v) => /^(true|yes|1)$/i.test(String(v).trim());

const out = ["-- Generated by scripts/migrate-from-sheets.mjs", "begin;"];
let maxSeq = 0;

const listings = parseCsv(readFileSync(listingsCsv, "utf8"));
for (const r of listings) {
  const id = r["Listing ID"];
  const contract = r["Contract Address"];
  if (!id || !contract) continue;
  const n = Number((id.match(/(\d+)$/) || [])[1] || 0);
  if (n > maxSeq) maxSeq = n;
  const links = {
    website: r["Website"], twitter: r["Twitter"], telegram: r["Telegram"], discord: r["Discord"], reddit: r["Reddit"],
    tiktok: r["TikTok"], youtube: r["YouTube"], github: r["GitHub"], medium: r["Medium"], linktree: r["Linktree"],
    audit: r["Audit"], other: r["Other Links"],
  };
  for (const k of Object.keys(links)) if (!links[k]) delete links[k];
  out.push(
    `insert into public.listings (id, user_id, username, project_name, symbol, chain, contract, pair_address, logo_url, banner_url, description, category, links, status, rejected_reason, featured, admin_votes, submitted_at, approved_at) values (` +
      [qs(id), "null", qs(r["Username"]), qs(r["Project Name"] || r["Symbol"] || contract), qs(r["Symbol"]), qs(r["Chain"] || "solana"), qs(contract),
        qs(r["Pair Address"]), qs(r["Logo URL"]), qs(r["Banner URL"]), qs(r["Description"]), qs(r["Category"]), `${qs(JSON.stringify(links))}::jsonb`,
        qs(status(r["Status"])), qs(r["Rejected Reason"]), truthy(r["Featured"]) ? "true" : "false", String(Math.max(0, parseInt(r["Vote Count"], 10) || 0)),
        `coalesce(${ts(r["Submitted Date"])}, now())`, ts(r["Approved Date"])].join(", ") +
      `) on conflict (id) do nothing;`,
  );
}
// New listings continue numbering after the highest imported ID.
if (maxSeq > 0) out.push(`select setval('public.listing_seq', ${maxSeq});`);

let votes = 0;
if (votesCsv) {
  for (const r of parseCsv(readFileSync(votesCsv, "utf8"))) {
    const chain = r["Chain"], address = r["Address"];
    if (!address) continue;
    // Keep the old voter id so the same browser can't vote twice after the move.
    const voter = r["Voter"] || `client:${r["Client ID"] || r["Vote ID"]}`;
    out.push(
      `insert into public.votes (coin_key, chain, address, name, symbol, voter, created_at) values (` +
        [qs(`${chain}:${address.toLowerCase()}`), qs(chain), qs(address), qs(r["Name"]), qs(r["Symbol"]), qs(voter), `coalesce(${ts(r["Timestamp"])}, now())`].join(", ") +
        `) on conflict (coin_key, voter) do nothing;`,
    );
    votes++;
  }
}

out.push("commit;");
console.log(out.join("\n"));
console.error(`Prepared ${listings.length} listings and ${votes} votes.`);
